export function snapshotRoadmap(roadmap) {
  const plain =
    typeof roadmap.toObject === 'function' ? roadmap.toObject() : structuredClone(roadmap);
  return {
    type: plain.type,
    title: plain.title,
    description: plain.description,
    summary: plain.summary,
    estimatedWeeks: plain.estimatedWeeks,
    currentLevel: plain.currentLevel,
    weeklyCommitmentHours: plain.weeklyCommitmentHours,
    confidence: plain.aiConfidence,
    missingSkills: plain.missingSkills,
    difficulty: plain.difficulty,
    completionCriteria: plain.completionCriteria,
    phases: plain.phases.map((phase) => ({
      key: phase.key,
      title: phase.title,
      description: phase.description,
      objective: phase.objective,
      estimatedWeeks: phase.estimatedWeeks,
      order: phase.order,
      state: phase.state,
      dependencies: phase.dependencies,
      milestones: phase.milestones,
      projects: phase.projects,
      checkpoints: phase.checkpoints,
      completionCriteria: phase.completionCriteria,
      weeks: phase.weeks.map((week) => ({
        key: week.key,
        title: week.title,
        description: week.description,
        objective: week.objective,
        weekNumber: week.weekNumber,
        order: week.order,
        state: week.state,
        dependencies: week.dependencies,
        milestones: week.milestones,
        projects: week.projects,
        checkpoints: week.checkpoints,
        completionCriteria: week.completionCriteria,
        tasks: week.tasks.map((task) => ({
          key: task.key,
          title: task.title,
          description: task.description,
          estimatedMinutes: task.estimatedMinutes,
          difficulty: task.difficulty,
          dependencies: task.dependencies,
          completionCriteria: task.completionCriteria,
          type: task.type,
          state: task.state,
          notes: task.notes.map((note) => ({
            noteId: note.noteId,
            content: note.content,
            createdAt: note.createdAt,
            updatedAt: note.updatedAt,
          })),
          resources: task.resources,
          learningExperience: task.learningExperience ?? null,
          attachments: (task.attachments ?? []).map((attachment) => ({
            attachmentId: attachment.attachmentId,
            type: attachment.type,
            url: attachment.url,
            title: attachment.title,
            description: attachment.description ?? null,
            metadata: attachment.metadata,
            createdAt: attachment.createdAt,
            updatedAt: attachment.updatedAt,
          })),
        })),
      })),
    })),
  };
}
