export const ROADMAP_WORKSPACE_ENDPOINTS = Object.freeze({
  list: defineEndpoint({
    id: 'roadmaps.list',
    method: 'GET',
    path: '/roadmaps',
    auth: true,
    dataSchema: {
      type: 'object',
      required: ['roadmaps'],
      properties: { roadmaps: { type: 'array', maxItems: 100, items: summary } },
      additionalProperties: false,
    },
  }),
  get: defineEndpoint({
    id: 'roadmaps.get',
    method: 'GET',
    path: '/roadmaps/:roadmapId',
    auth: true,
    paramsSchema: roadmapIdParams,
    dataSchema: workspaceData,
  }),
  update: defineEndpoint({
    id: 'roadmaps.update',
    method: 'PATCH',
    path: '/roadmaps/:roadmapId',
    auth: true,
    csrf: true,
    paramsSchema: roadmapIdParams,
    bodySchema: {
      type: 'object',
      required: ['revision', 'changes'],
      properties: {
        ...mutationBase,
        confirmedProtectedEdit: { type: 'boolean' },
        changes: {
          type: 'object',
          minProperties: 1,
          properties: {
            title: { type: 'string', minLength: 1, maxLength: 300 },
            description: { type: 'string', minLength: 1, maxLength: 5000 },
          },
          additionalProperties: false,
        },
      },
      additionalProperties: false,
    },
    dataSchema: workspaceData,
  }),
  createNode: defineEndpoint({
    id: 'roadmaps.nodes.create',
    method: 'POST',
    path: '/roadmaps/:roadmapId/nodes',
    auth: true,
    csrf: true,
    paramsSchema: roadmapIdParams,
    bodySchema: {
      type: 'object',
      required: ['revision', 'nodeType', 'parentKey', 'data'],
      properties: {
        ...mutationBase,
        confirmedProtectedEdit: { type: 'boolean' },
        nodeType: { enum: ['phase', 'week', 'task'] },
        parentKey: { type: ['string', 'null'] },
        afterKey: { type: ['string', 'null'] },
        data: {
          type: 'object',
          required: ['title'],
          properties: {
            title: { type: 'string', minLength: 1, maxLength: 300 },
            description: { type: 'string', maxLength: 5000 },
            estimatedMinutes: { type: 'integer', minimum: 5, maximum: 2400 },
            difficulty: { enum: ['beginner', 'intermediate', 'advanced', 'expert'] },
            type: { enum: ['learn', 'practice', 'project', 'assessment', 'checkpoint'] },
          },
          additionalProperties: false,
        },
      },
      additionalProperties: false,
    },
    dataSchema: workspaceData,
  }),
  updateNode: defineEndpoint({
    id: 'roadmaps.nodes.update',
    method: 'PATCH',
    path: '/roadmaps/:roadmapId/nodes/:nodeType/:nodeKey',
    auth: true,
    csrf: true,
    paramsSchema: nodeParams,
    bodySchema: {
      type: 'object',
      required: ['revision', 'changes'],
      properties: {
        ...mutationBase,
        confirmedProtectedEdit: { type: 'boolean' },
        changes: {
          type: 'object',
          minProperties: 1,
          properties: {
            title: { type: 'string', minLength: 1, maxLength: 300 },
            description: { type: 'string', minLength: 1, maxLength: 5000 },
            estimatedMinutes: { type: 'integer', minimum: 5, maximum: 2400 },
            state: { enum: ['NOT_STARTED', 'IN_PROGRESS', 'COMPLETED', 'LOCKED'] },
            notes: {
              type: 'array',
              maxItems: 100,
              items: {
                type: 'object',
                required: ['content'],
                properties: {
                  noteId: { type: 'string' },
                  content: { type: 'string', minLength: 1, maxLength: 10000 },
                },
                additionalProperties: false,
              },
            },
            attachments: {
              type: 'array',
              maxItems: 50,
              items: {
                type: 'object',
                required: ['type', 'url'],
                properties: {
                  attachmentId: { type: 'string', format: 'uuid' },
                  type: {
                    enum: ['youtube', 'github', 'pdf', 'google_doc', 'external_url'],
                  },
                  url: { type: 'string', format: 'uri', maxLength: 2000 },
                  title: { type: 'string', maxLength: 500 },
                  description: { type: ['string', 'null'], maxLength: 2000 },
                },
                additionalProperties: false,
              },
            },
          },
          additionalProperties: false,
        },
      },
      additionalProperties: false,
    },
    dataSchema: workspaceData,
  }),
  deleteNode: defineEndpoint({
    id: 'roadmaps.nodes.delete',
    method: 'DELETE',
    path: '/roadmaps/:roadmapId/nodes/:nodeType/:nodeKey',
    auth: true,
    csrf: true,
    paramsSchema: nodeParams,
    bodySchema: {
      type: 'object',
      required: ['revision'],
      properties: { ...mutationBase, confirmedProtectedEdit: { type: 'boolean' } },
      additionalProperties: false,
    },
    dataSchema: workspaceData,
  }),
  visibility: defineEndpoint({
    id: 'roadmaps.visibility.update',
    method: 'PATCH',
    path: '/roadmaps/:roadmapId/visibility',
    auth: true,
    csrf: true,
    paramsSchema: roadmapIdParams,
    bodySchema: {
      type: 'object',
      required: ['revision', 'visibility'],
      properties: {
        revision: { type: 'integer', minimum: 0 },
        visibility: { enum: ['PRIVATE', 'PUBLIC'] },
      },
      additionalProperties: false,
    },
    dataSchema: workspaceData,
  }),
  duplicate: defineEndpoint({
    id: 'roadmaps.duplicate',
    method: 'POST',
    path: '/roadmaps/:roadmapId/duplicate',
    auth: true,
    csrf: true,
    paramsSchema: roadmapIdParams,
    bodySchema: { type: 'object', properties: {}, additionalProperties: false },
    dataSchema: workspaceData,
  }),
  remove: defineEndpoint({
    id: 'roadmaps.delete',
    method: 'DELETE',
    path: '/roadmaps/:roadmapId',
    auth: true,
    csrf: true,
    paramsSchema: roadmapIdParams,
    bodySchema: { type: 'object', properties: {}, additionalProperties: false },
    dataSchema: {
      type: 'object',
      required: ['roadmapId', 'deletedAt'],
      properties: {
        roadmapId: { type: 'string', format: 'uuid' },
        deletedAt: { type: 'string', format: 'date-time' },
      },
      additionalProperties: false,
    },
  }),
});
